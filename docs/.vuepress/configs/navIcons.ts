import {
  ensureEndingSlash,
  isLinkAbsolute,
  isLinkWithProtocol,
} from '@vuepress/helper'
import type {
  NavbarGroupOptions,
  NavbarLinkOptions,
  NavbarOptions,
  SidebarGroupOptions,
  SidebarItemOptions,
  SidebarOptions,
} from '@vuepress/theme-classic'

type NavItem =
  | NavbarGroupOptions
  | NavbarLinkOptions
  | SidebarGroupOptions
  | SidebarItemOptions

const resolvePrefix = (prefix: string, path: string): string =>
  isLinkAbsolute(path) || isLinkWithProtocol(path)
    ? path
    : `${ensureEndingSlash(prefix)}${path}`

const collectIcons = (
  items: NavItem[],
  prefix: string,
  result: Map<string, string>,
): void => {
  for (const item of items) {
    if (typeof item === 'string') continue

    const itemPrefix = 'prefix' in item ? item.prefix : undefined
    const link = 'link' in item ? item.link : undefined
    const childPrefix = itemPrefix ? resolvePrefix(prefix, itemPrefix) : prefix
    const path = link
      ? resolvePrefix(prefix, link)
      : itemPrefix
        ? childPrefix
        : ''

    if (path && item.icon) result.set(path, item.icon)

    if ('children' in item) collectIcons(item.children, childPrefix, result)
  }
}

/**
 * Collect the page icons from the nav configs, so that pages which are not
 * present on the file system (e.g. the ones generated by `catalogPlugin`) can
 * reuse the icon of the matching nav item.
 *
 * @param navbars - Navbar configs
 * @param sidebars - Sidebar configs
 * @returns A map of page path to icon
 */
export const getNavIcons = (
  navbars: NavbarOptions[],
  sidebars: SidebarOptions[],
): Map<string, string> => {
  const result = new Map<string, string>()

  const collect = (
    config: NavbarOptions | SidebarOptions,
    prefix: string,
  ): void => {
    if (config === false || typeof config === 'string') return

    if (Array.isArray(config)) collectIcons(config, prefix, result)
    else
      for (const [base, items] of Object.entries(config)) collect(items, base)
  }

  for (const navbar of navbars) collect(navbar, '/')
  for (const sidebar of sidebars) collect(sidebar, '/')

  return result
}
